// Helper to generate step array quickly
export function createEmptySteps(count: number = 16): StepData[] {
  return Array.from({ length: count }, () => ({
    active: false,
    velocity: 90,
    probability: 1.0,
    ratchet: 1,
  }));
}

export function createStepPattern(
  activeIndices: number[],
  velocities?: Record<number, number>,
  ratchets?: Record<number, number>,
  count: number = 16
): StepData[] {
  const steps = createEmptySteps(count);
  activeIndices.forEach((idx) => {
    if (idx < count) {
      steps[idx] = {
        active: true,
        velocity: velocities?.[idx] ?? 90,
        probability: 1.0,
        ratchet: ratchets?.[idx] ?? 1,
      };
    }
  });
  return steps;
}

